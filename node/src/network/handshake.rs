//! Bounded, signed peer-hello primitive. NOT a TCP transport or an authenticated
//! session: callers must enforce fresh challenges, deadlines and replay protection
//! before using a verified identity to admit a network peer.
use ed25519_dalek::{Signature, Verifier, VerifyingKey};
use sha2::{Digest, Sha256};

const DOMAIN: &[u8] = b"AIVOBLOCK-PEER-HELLO-V1\0";
pub const HELLO_VERSION: u32 = 1;
pub const HELLO_BYTES: usize = 4 + 4 + 32 + 32 + 64;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VerifiedHello {
    pub peer_id: [u8; 32],
    pub public_key: [u8; 32],
    pub challenge: [u8; 32],
}

/// Fixed-size wire encoding:
/// version:u32_be || chain_id:u32_be || public_key:32 || challenge:32 || signature:64.
/// The signature covers the domain and all fields preceding it.
/// The challenge MUST be generated by the verifier, checked against an outstanding
/// pending handshake, and consumed once. This helper only checks its exact value.
pub fn verify_hello(
    message: &[u8],
    expected_chain_id: u32,
    expected_challenge: &[u8; 32],
) -> Result<VerifiedHello, &'static str> {
    if message.len() != HELLO_BYTES {
        return Err("Wrong hello length");
    }
    if expected_chain_id == 0 || *expected_challenge == [0; 32] {
        return Err("Invalid local handshake configuration");
    }
    let version = u32::from_be_bytes(message[0..4].try_into().unwrap());
    let chain_id = u32::from_be_bytes(message[4..8].try_into().unwrap());
    if version != HELLO_VERSION || chain_id != expected_chain_id {
        return Err("Peer protocol version or chain ID mismatch");
    }
    let public_key: [u8; 32] = message[8..40].try_into().unwrap();
    let challenge: [u8; 32] = message[40..72].try_into().unwrap();
    if challenge != *expected_challenge {
        return Err("Unrecognized handshake challenge");
    }
    let verifying_key = VerifyingKey::from_bytes(&public_key)
        .map_err(|_| "Invalid peer public key")?;
    let signature_bytes: [u8; 64] = message[72..136].try_into().unwrap();
    let signature = Signature::from_bytes(&signature_bytes);
    let mut preimage = Vec::with_capacity(DOMAIN.len() + 72);
    preimage.extend_from_slice(DOMAIN);
    preimage.extend_from_slice(&message[..72]);
    verifying_key.verify(&preimage, &signature)
        .map_err(|_| "Invalid peer hello signature")?;
    let peer_id: [u8; 32] = Sha256::digest(public_key).into();
    Ok(VerifiedHello { peer_id, public_key, challenge })
}

#[cfg(test)]
mod tests {
    use super::*;
    use ed25519_dalek::{Signer, SigningKey};

    fn signed_hello(chain: u32, challenge: [u8; 32]) -> Vec<u8> {
        let key = SigningKey::from_bytes(&[7; 32]);
        let mut bytes = Vec::with_capacity(HELLO_BYTES);
        bytes.extend_from_slice(&HELLO_VERSION.to_be_bytes());
        bytes.extend_from_slice(&chain.to_be_bytes());
        bytes.extend_from_slice(&key.verifying_key().to_bytes());
        bytes.extend_from_slice(&challenge);
        let mut payload = DOMAIN.to_vec();
        payload.extend_from_slice(&bytes);
        bytes.extend_from_slice(&key.sign(&payload).to_bytes());
        bytes
    }

    #[test]
    fn accepts_valid_signed_hello() {
        let challenge = [5; 32];
        let verified = verify_hello(&signed_hello(1, challenge), 1, &challenge).unwrap();
        assert_eq!(verified.challenge, challenge);
        assert_ne!(verified.peer_id, [0; 32]);
    }

    #[test]
    fn rejects_mismatched_chain_version_and_challenge() {
        let challenge = [5; 32];
        assert!(verify_hello(&signed_hello(2, challenge), 1, &challenge).is_err());
        assert!(verify_hello(&signed_hello(1, challenge), 1, &[6; 32]).is_err());
        let mut message = signed_hello(1, challenge);
        message[3] = 2;
        assert!(verify_hello(&message, 1, &challenge).is_err());
    }

    #[test]
    fn rejects_tampering_forgery_and_frame_size() {
        let challenge = [5; 32];
        let message = signed_hello(1, challenge);
        for index in [8usize, 40, 71, 72, 135] {
            let mut tampered = message.clone();
            tampered[index] ^= 1;
            assert!(verify_hello(&tampered, 1, &challenge).is_err());
        }
        assert!(verify_hello(&message[..135], 1, &challenge).is_err());
        let mut extended = message.clone();
        extended.push(0);
        assert!(verify_hello(&extended, 1, &challenge).is_err());
        assert!(verify_hello(&message, 0, &challenge).is_err());
        assert!(verify_hello(&message, 1, &[0; 32]).is_err());
    }
}
